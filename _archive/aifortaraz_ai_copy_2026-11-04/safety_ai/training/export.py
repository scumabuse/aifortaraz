@dataclass(frozen=True, slots=True, eq=False)
class VerifyImage:
    """One verification image with a label for the report and where it came from."""

    label: str
    image: ImageArray
    source: str = "caller-supplied images"


def load_image(path: Path) -> ImageArray:
    """Read a BGR image (works with non-ASCII paths on Windows).

    Raises:
        ValueError: When the file cannot be decoded.
    """
    data = np.fromfile(str(path), dtype=np.uint8)
    image = cv2.imdecode(data, cv2.IMREAD_COLOR)
    if image is None:
        raise ValueError(f"cannot decode image {path}")
    return cast(ImageArray, image)


def augment_image(image: ImageArray, rng: np.random.Generator) -> tuple[ImageArray, str]:
    """Return a deterministic (given ``rng``) augmentation of ``image`` and its description.

    A random crop keeping 70-100 % of each side, an optional horizontal flip, a rotation within
    +/-8 degrees (reflected border) and a brightness/contrast change.
    """
    height, width = image.shape[:2]
    keep_w = float(rng.uniform(0.7, 1.0))
    keep_h = float(rng.uniform(0.7, 1.0))
    crop_w, crop_h = max(32, int(width * keep_w)), max(32, int(height * keep_h))
    x0 = int(rng.integers(0, width - crop_w + 1))
    y0 = int(rng.integers(0, height - crop_h + 1))
    out = image[y0 : y0 + crop_h, x0 : x0 + crop_w].copy()
    flip = bool(rng.integers(0, 2))
    if flip:
        out = cv2.flip(out, 1)
    angle = float(rng.uniform(-8.0, 8.0))
    matrix = cv2.getRotationMatrix2D((crop_w / 2.0, crop_h / 2.0), angle, 1.0)
    out = cv2.warpAffine(out, matrix, (crop_w, crop_h), borderMode=cv2.BORDER_REFLECT_101)
    alpha = float(rng.uniform(0.75, 1.25))
    beta = float(rng.uniform(-25.0, 25.0))
    out = cv2.convertScaleAbs(out, alpha=alpha, beta=beta)
    note = (
        f"crop {keep_w:.2f}x{keep_h:.2f}{', flip' if flip else ''}, rot {angle:+.1f} deg, "
        f"contrast {alpha:.2f}, brightness {beta:+.0f}"
    )
    return cast(ImageArray, out), note


def default_verify_images(
    count: int = VERIFY_IMAGES, *, data_yaml: Path = DEFAULT_DATA_YAML, seed: int = 0
) -> list[VerifyImage]:
    """Return ``count`` verification images (spec 6.6).

    A seeded random sample of the val split of ``data_yaml`` when that dataset exists, else the
    images shipped with Ultralytics (bus.jpg, zidane.jpg) unchanged followed by deterministic
    augmentations of them.
    """
    if count < 1:
        raise ValueError("count must be >= 1")
    if Path(data_yaml).is_file():
        spec = load_dataset_spec(data_yaml)
        images = list_images(spec.sources("val"), unique=True)
        if images:
            picked = images if len(images) <= count else random.Random(seed).sample(images, count)
            source = f"{display_path(spec.yaml_path)} val split (seeded sample)"
            return [
                VerifyImage(display_path(p), load_image(p), source) for p in sorted(picked, key=str)
            ]
    assets = sorted(p for p in Path(ASSETS).iterdir() if p.suffix.lower() in {".jpg", ".png"})
    if not assets:
        raise FileNotFoundError(f"no images in the Ultralytics assets folder {ASSETS}")
    originals = [(p.name, load_image(p)) for p in assets]
    source = "Ultralytics assets plus deterministic augmentations"
    out = [VerifyImage(name, image, source) for name, image in originals[:count]]
    rng = np.random.default_rng(seed)
    while len(out) < count:
        name, image = originals[len(out) % len(originals)]
        augmented, note = augment_image(image, rng)
        out.append(VerifyImage(f"{name} ({note})", augmented, source))
    return out


def _as_verify_images(
    images: Sequence[VerifyImage | ImageArray | Path | str],
) -> list[VerifyImage]:
    """Normalize caller input to :class:`VerifyImage` objects."""
    out: list[VerifyImage] = []
    for index, item in enumerate(images):
        if isinstance(item, VerifyImage):
            out.append(item)
        elif isinstance(item, (Path, str)):
            out.append(VerifyImage(display_path(Path(item)), load_image(Path(item))))
        else:
            out.append(VerifyImage(f"image {index}", item))
    return out


