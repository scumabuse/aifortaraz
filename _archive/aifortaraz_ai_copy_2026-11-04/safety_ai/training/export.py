@dataclass(frozen=True, slots=True)
class Box:
    """A detection or label box: class id, normalized corners ``(x1, y1, x2, y2)``, confidence."""

    cls: int
    x1: float
    y1: float
    x2: float
    y2: float
    conf: float = 1.0

    @property
    def area(self) -> float:
        """Box area (0 for degenerate boxes)."""
        return max(0.0, self.x2 - self.x1) * max(0.0, self.y2 - self.y1)


def box_iou(a: Box, b: Box) -> float:
    """Intersection over union of two boxes (0 when either is degenerate)."""
    inter_w = min(a.x2, b.x2) - max(a.x1, b.x1)
    inter_h = min(a.y2, b.y2) - max(a.y1, b.y1)
    if inter_w <= 0 or inter_h <= 0:
        return 0.0
    inter = inter_w * inter_h
    union = a.area + b.area - inter
    return inter / union if union > 0 else 0.0


@dataclass(frozen=True, slots=True)
class BoxMatch:
    """A matched pair: index into the reference list, index into the candidate list, IoU."""

    reference: int
    candidate: int
    iou: float


@dataclass(frozen=True, slots=True)
class MatchResult:
    """Outcome of :func:`match_boxes`."""

    matched: tuple[BoxMatch, ...]
    """Same-class pairs."""
    class_mismatches: tuple[BoxMatch, ...]
    """Pairs of leftover boxes that overlap (IoU >= min_iou) but carry different class ids."""
    unmatched_reference: tuple[int, ...]
    unmatched_candidate: tuple[int, ...]

    @property
    def mean_iou(self) -> float | None:
        """Mean IoU of the same-class pairs; None when nothing matched."""
        if not self.matched:
            return None
        return sum(m.iou for m in self.matched) / len(self.matched)


def _greedy(pairs: Iterable[tuple[float, int, int]]) -> list[BoxMatch]:
    """Take pairs by descending IoU (ties: lower indices first), each box at most once."""
    taken_ref: set[int] = set()
    taken_cand: set[int] = set()
    chosen: list[BoxMatch] = []
    for iou, ref, cand in sorted(pairs, key=lambda p: (-p[0], p[1], p[2])):
        if ref in taken_ref or cand in taken_cand:
            continue
        taken_ref.add(ref)
        taken_cand.add(cand)
        chosen.append(BoxMatch(ref, cand, iou))
    return chosen


def match_boxes(
    reference: Sequence[Box],
    candidate: Sequence[Box],
    *,
    min_iou: float = MATCH_IOU,
    cross_class: bool = True,
) -> MatchResult:
    """Match boxes per class, greedily by descending IoU (spec 6.6).

    Pairs need the same class and IoU >= ``min_iou``. With ``cross_class``, the leftover boxes
    are then paired across classes the same way; such pairs are the same object with a changed
    class id and are reported as ``class_mismatches``. Everything left is unmatched.
    """
    same = [
        (iou, i, j)
        for i, ref in enumerate(reference)
        for j, cand in enumerate(candidate)
        if ref.cls == cand.cls and (iou := box_iou(ref, cand)) >= min_iou
    ]
    matched = _greedy(same)
    used_ref = {m.reference for m in matched}
    used_cand = {m.candidate for m in matched}
    mismatches: list[BoxMatch] = []
    if cross_class:
        cross = [
            (iou, i, j)
            for i, ref in enumerate(reference)
            if i not in used_ref
            for j, cand in enumerate(candidate)
            if j not in used_cand and ref.cls != cand.cls and (iou := box_iou(ref, cand)) >= min_iou
        ]
        mismatches = _greedy(cross)
        used_ref |= {m.reference for m in mismatches}
        used_cand |= {m.candidate for m in mismatches}
    return MatchResult(
        matched=tuple(matched),
        class_mismatches=tuple(mismatches),
        unmatched_reference=tuple(i for i in range(len(reference)) if i not in used_ref),
        unmatched_candidate=tuple(j for j in range(len(candidate)) if j not in used_cand),
    )


def _as_list(value: Any) -> list[Any]:
    """Convert a tensor/array/sequence to a plain list."""
    if hasattr(value, "tolist"):
        return list(value.tolist())
    return list(value)


def result_boxes(result: Any) -> list[Box]:
    """Return the boxes of one Ultralytics ``Results`` (normalized xyxy, class, confidence)."""
    boxes = getattr(result, "boxes", None)
    if boxes is None:
        return []
    corners = _as_list(boxes.xyxyn)
    classes = _as_list(boxes.cls)
    confs = _as_list(boxes.conf)
    return [
        Box(int(c), float(xy[0]), float(xy[1]), float(xy[2]), float(xy[3]), float(p))
        for xy, c, p in zip(corners, classes, confs, strict=True)
    ]


