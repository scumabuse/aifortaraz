"""Export registered models to ONNX, OpenVINO and TensorRT and verify them (spec 6.6, 6.7).

:func:`export` converts a registry entry's ``.pt`` weights (the PPE detector or the pose model,
e.g. ``pose_n``) with the Ultralytics Python API and records every artefact under the entry's
``exports`` map with its sha256:

* **ONNX**: opset 17, fixed ``imgsz``, batch 1, graph simplified (onnxslim), FP32.
* **OpenVINO** (CPU runtime): FP32 IR. OpenVINO's CPU plugin computes in FP32 (or BF16 on CPUs
  with AMX/AVX512-BF16) whatever the IR's weight precision, so an FP16-compressed IR would only
  halve the file size while adding a rounding step between the verified ``.pt`` and the IR.
* **TensorRT**: FP16 engine, only when CUDA and the ``tensorrt`` module are available; otherwise
  the format is reported as skipped with the reason. Engines are specific to the GPU and the
  TensorRT version (D-025: git-ignored, regenerated by ``make models``).

Each export runs in a scratch directory next to the weights and only the requested artefact is
moved into place, so a TensorRT export never overwrites the registered ONNX file with its own
intermediate ONNX. The FP16/FP32 keyword (``quantize`` in Ultralytics 8.4, ``half`` before) is
detected at runtime (D-009).

:func:`verify_export` runs the same images (20 by default: a seeded sample of the val split of
``data/merged`` when present, else the images shipped with Ultralytics plus deterministic
augmentations) through the export and the ``.pt`` model with identical preprocessing (square
letterbox at the export's fixed size), matches boxes per class greedily by descending IoU
(:func:`match_boxes`) and passes when the mean IoU of the matched boxes is >= 0.9 and no matched
box changed its class id. Unmatched boxes are reported, not failed: detections near the
confidence threshold may legitimately flip in or out. The result is written to
``reports/export_verify_<model>_<fmt>.md``.
"""

