def _summarize(
    label: str, reference: Sequence[Box], candidate: Sequence[Box], result: MatchResult
) -> ImageComparison:
    """Summarize one image's match result."""
    ious = [m.iou for m in result.matched]
    return ImageComparison(
        label=label,
        reference_boxes=len(reference),
        export_boxes=len(candidate),
        matched=len(result.matched),
        mean_iou=result.mean_iou,
        min_iou=min(ious) if ious else None,
        class_mismatches=len(result.class_mismatches),
        unmatched_reference=len(result.unmatched_reference),
        unmatched_export=len(result.unmatched_candidate),
    )


def _predictor_imgsz(model: Any) -> tuple[int, int] | None:
    """The ``(h, w)`` Ultralytics actually used (fixed exports force their metadata size)."""
    size = getattr(getattr(model, "predictor", None), "imgsz", None)
    if isinstance(size, (list, tuple)) and len(size) == 2:
        return int(size[0]), int(size[1])
    return None


def _predict_all(
    model: PredictModel, images: Sequence[VerifyImage], **kwargs: Any
) -> list[list[Box]]:
    """Predict every image one by one and return its boxes."""
    out: list[list[Box]] = []
    for item in images:
        results = model.predict(item.image, **kwargs)
        out.append(result_boxes(results[0]) if results else [])
    return out


def _verdict(
    matched: int, mean_iou: float | None, mismatches: int, min_mean_iou: float
) -> tuple[bool, str]:
    """Apply the spec 6.6 criteria and explain the outcome."""
    if matched == 0 or mean_iou is None:
        return False, "no box of the .pt model was matched by the export, so nothing is verified"
    if mismatches:
        return False, f"{mismatches} matched box(es) changed their class id"
    if mean_iou < min_mean_iou:
        return False, f"mean IoU {mean_iou:.4f} of matched boxes is below {min_mean_iou}"
    return True, f"mean IoU {mean_iou:.4f} >= {min_mean_iou} and identical class ids"


def verify_export(
    model_name: str,
    fmt: str,
    images: Sequence[VerifyImage | ImageArray | Path | str] | None = None,
    *,
    conf: float = 0.25,
    registry: ModelRegistry | None = None,
    device: str = "cpu",
    imgsz: int | None = None,
    reports_dir: Path = Path("reports"),
    min_mean_iou: float = MIN_MEAN_IOU,
    model_factory: Callable[[str], PredictModel] | None = None,
    clock: Clock | None = None,
) -> VerifyResult:
    """Compare an export with the ``.pt`` model on the same images (spec 6.6).

    Both models see identical inputs: square letterbox (``rect=False``) at the export's fixed size
    (read back from the export's predictor; ``imgsz`` or the entry's imgsz otherwise), the same
    ``conf`` and device. TensorRT always runs on CUDA. Writes
    ``<reports_dir>/export_verify_<model>_<fmt>.md``.

    Args:
        model_name: Registry name or alias.
        fmt: ``onnx``, ``openvino`` or ``tensorrt``.
        images: Images, paths or :class:`VerifyImage` objects; None = :func:`default_verify_images`.
        conf: Confidence threshold of both models (the deployed default).
        registry: Registry holding the entry and its export.
        device: Inference device of both models.
        imgsz: Input size override.
        reports_dir: Where the markdown report goes.
        min_mean_iou: Pass threshold for the mean IoU of matched boxes.
        model_factory: Loads a model for prediction (default ``ultralytics.YOLO``).
        clock: Time source of the report timestamp.

    Raises:
        RegistryError: When the entry or its ``fmt`` export does not exist.
    """
    registry = registry or ModelRegistry()
    clock = clock or SystemClock()
    factory = model_factory or _load_predict_model
    wanted = normalize_format(fmt)
    entry: RegistryEntry = registry.resolve(model_name)
    reference_path = registry.resolve_path(entry)
    export_path = registry.resolve_path(entry, wanted)
    run_device = _export_device(wanted, device)
    items = _as_verify_images(images) if images is not None else default_verify_images()
    if not items:
        raise ValueError("verify_export needs at least one image")
    size = imgsz or entry.imgsz
    options: dict[str, Any] = {"conf": conf, "rect": False, "verbose": False}
    options["device"] = ultralytics_device(run_device)

    export_model = factory(str(export_path))
    exported = _predict_all(export_model, items, imgsz=size, **options)
    used = _predictor_imgsz(export_model) or (size, size)
    reference_model = factory(str(reference_path))
    reference = _predict_all(reference_model, items, imgsz=list(used), **options)

    matches = [match_boxes(ref, cand) for ref, cand in zip(reference, exported, strict=True)]
    comparisons = tuple(
        _summarize(item.label, ref, cand, res)
        for item, ref, cand, res in zip(items, reference, exported, matches, strict=True)
    )
    ious = [m.iou for res in matches for m in res.matched]
    matched = len(ious)
    mean_iou = sum(ious) / matched if matched else None
    mismatches = sum(c.class_mismatches for c in comparisons)
    passed, reason = _verdict(matched, mean_iou, mismatches, min_mean_iou)
    report_path = Path(reports_dir) / f"export_verify_{entry.name}_{wanted}.md"
    result = VerifyResult(
        model_name=entry.name,
        format=wanted,
        reference_path=reference_path,
        export_path=export_path,
        images=len(items),
        image_source="; ".join(dict.fromkeys(item.source for item in items)),
        conf=conf,
        imgsz=used,
        device=run_device,
        matched=matched,
        mean_iou=mean_iou,
        min_iou=min(ious, default=None),
        class_mismatches=mismatches,
        unmatched_reference=sum(c.unmatched_reference for c in comparisons),
        unmatched_export=sum(c.unmatched_export for c in comparisons),
        passed=passed,
        reason=reason,
        comparisons=comparisons,
        report_path=report_path,
        verified_at=format_utc_seconds(clock.now_utc()),
    )
    atomic_write_text(report_path, render_verify_report(result, min_mean_iou=min_mean_iou))
    return result


def _fmt_iou(value: float | None) -> str:
    """Render an IoU or a dash."""
    return f"{value:.4f}" if value is not None else "—"


def render_verify_report(result: VerifyResult, *, min_mean_iou: float = MIN_MEAN_IOU) -> str:
    """Return the markdown report of a verification (pure)."""
    verdict = "PASSED" if result.passed else "FAILED"
    height, width = result.imgsz
    lines = [
        f"# Export verification — {result.model_name} ({result.format})",
        "",
        f"**{verdict}**: {result.reason}.",
        "",
        "| item | value |",
        "|---|---|",
        f"| verified (UTC) | {result.verified_at} |",
        f"| reference | {display_path(result.reference_path)} (PyTorch) |",
        f"| export | {display_path(result.export_path)} |",
        f"| images | {result.images} ({result.image_source}) |",
        f"| input | {width}x{height} square letterbox, batch 1, same for both models |",
        f"| confidence threshold | {result.conf} |",
        f"| device | {result.device} |",
        f"| matching | per class, greedy by descending IoU, a pair needs IoU >= {MATCH_IOU}; "
        f"leftover overlapping boxes with different class ids count as class mismatches |",
        f"| pass criteria | mean IoU of matched boxes >= {min_mean_iou} and no class mismatch |",
        f"| matched boxes | {result.matched} |",
        f"| mean IoU (min) | {_fmt_iou(result.mean_iou)} ({_fmt_iou(result.min_iou)}) |",
        f"| class mismatches | {result.class_mismatches} |",
        f"| unmatched .pt boxes | {result.unmatched_reference} |",
        f"| unmatched export boxes | {result.unmatched_export} |",
        "",
        "Unmatched boxes are reported but do not fail the check: detections whose confidence is "
        "within rounding of the threshold can appear in one backend and not the other.",
        "",
        "## Per image",
        "",
        "| # | image | .pt boxes | export boxes | matched | mean IoU | min IoU "
        "| class mismatches | unmatched .pt | unmatched export |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for index, c in enumerate(result.comparisons, start=1):
        lines.append(
            f"| {index} | {c.label.replace('|', '/')} | {c.reference_boxes} | {c.export_boxes} "
            f"| {c.matched} | {_fmt_iou(c.mean_iou)} | {_fmt_iou(c.min_iou)} "
            f"| {c.class_mismatches} | {c.unmatched_reference} | {c.unmatched_export} |"
        )
    lines.append("")
    return "\n".join(lines)
