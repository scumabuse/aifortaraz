class ExportModel(Protocol):
    """The part of ``ultralytics.YOLO`` used for exporting."""

    def export(self, **kwargs: Any) -> Any:
        """Export with Ultralytics keyword arguments; return the artefact path."""
        ...


class PredictModel(Protocol):
    """The part of ``ultralytics.YOLO`` used for verification and evaluation."""

    def predict(self, source: Any = None, **kwargs: Any) -> list[Any]:
        """Run inference and return one ``Results`` per image."""
        ...


def _load_export_model(weights: str) -> ExportModel:
    """Load ``weights`` with Ultralytics for exporting."""
    return cast(ExportModel, YOLO(weights))


def _load_predict_model(weights: str) -> PredictModel:
    """Load weights or an exported model with Ultralytics for prediction."""
    return cast(PredictModel, YOLO(weights))


@dataclass(frozen=True, slots=True)
class ExportArtifact:
    """One produced export."""

    format: ExportFormat
    path: Path
    sha256: str
    imgsz: int
    precision: str
    seconds: float


@dataclass(frozen=True, slots=True)
class SkippedExport:
    """A requested format that could not be produced on this machine."""

    format: ExportFormat
    reason: str


@dataclass(frozen=True, slots=True)
class ExportResult:
    """Outcome of :func:`export`."""

    model_name: str
    weights: Path
    artifacts: tuple[ExportArtifact, ...]
    skipped: tuple[SkippedExport, ...]

    def artifact(self, fmt: str) -> ExportArtifact | None:
        """Return the artefact of ``fmt`` (aliases accepted) or None."""
        wanted = normalize_format(fmt)
        return next((a for a in self.artifacts if a.format == wanted), None)


def normalize_format(fmt: str) -> ExportFormat:
    """Map ``onnx``/``openvino``/``tensorrt`` (``engine``, ``trt``) to the registry format name.

    Raises:
        ValueError: For any other format.
    """
    key = fmt.strip().lower()
    if key not in _FORMAT_ALIASES:
        raise ValueError(f"unsupported export format {fmt!r}; choose from {DEFAULT_FORMATS}")
    return _FORMAT_ALIASES[key]


def precision_kwargs(fp16: bool) -> dict[str, Any]:
    """Return the precision keyword the installed Ultralytics understands (D-009)."""
    if "quantize" in DEFAULT_CFG_DICT:
        return {"quantize": 16} if fp16 else {}
    return {"half": fp16}


def export_kwargs(fmt: ExportFormat, *, imgsz: int, device: str) -> dict[str, Any]:
    """Return the ``YOLO.export`` keyword arguments for one format (fixed size, batch 1)."""
    common: dict[str, Any] = {
        "format": _ULTRALYTICS_FORMAT[fmt],
        "imgsz": imgsz,
        "batch": 1,
        "dynamic": False,
        "device": ultralytics_device(device),
    }
    if fmt == "onnx":
        return {**common, "opset": ONNX_OPSET, "simplify": True, **precision_kwargs(False)}
    if fmt == "openvino":
        return {**common, **precision_kwargs(False)}
    return {**common, "simplify": True, **precision_kwargs(True)}


def export_unavailable_reason(
    fmt: ExportFormat,
    *,
    cuda_available: bool | None = None,
    module_available: Callable[[str], bool] | None = None,
) -> str | None:
    """Return why ``fmt`` cannot be exported here, or None when it can.

    Missing modules are reported instead of letting Ultralytics try to pip-install them.
    """
    has_module = module_available or (lambda name: importlib.util.find_spec(name) is not None)
    if fmt == "tensorrt":
        has_cuda = torch.cuda.is_available() if cuda_available is None else cuda_available
        if not has_cuda:
            return "TensorRT needs a CUDA GPU and CUDA is not available"
    missing = [name for name in _REQUIRED_MODULES[fmt] if not has_module(name)]
    if missing:
        return f"Python module(s) {', '.join(missing)} not installed (optional, spec 9)"
    return None


def _export_device(fmt: ExportFormat, device: str) -> str:
    """TensorRT always builds on a CUDA device; ONNX and OpenVINO use ``device``."""
    if fmt == "tensorrt":
        return device if device.startswith("cuda") else "cuda:0"
    return device


def _replace_path(src: Path, dst: Path) -> None:
    """Move ``src`` (file or directory) to ``dst``, replacing what is there."""
    if dst.is_dir():
        shutil.rmtree(dst)
    elif dst.exists():
        dst.unlink()
    shutil.move(str(src), str(dst))


def _export_one(
    weights: Path,
    fmt: ExportFormat,
    *,
    imgsz: int,
    device: str,
    factory: Callable[[str], ExportModel],
    clock: Clock,
) -> ExportArtifact:
    """Export ``weights`` to ``fmt`` in a scratch directory and move the artefact next to it."""
    started = clock.monotonic()
    dest_dir = weights.parent
    with tempfile.TemporaryDirectory(
        prefix=f".export-{weights.stem}-", dir=dest_dir, ignore_cleanup_errors=True
    ) as scratch:
        work = Path(scratch) / weights.name
        shutil.copyfile(weights, work)
        model = factory(str(work))
        produced = model.export(**export_kwargs(fmt, imgsz=imgsz, device=device))
        if not produced:
            raise RuntimeError(f"Ultralytics produced no {fmt} export for {weights}")
        produced_path = Path(str(produced))
        final = dest_dir / produced_path.name
        _replace_path(produced_path, final)
    return ExportArtifact(
        format=fmt,
        path=final,
        sha256=sha256_path(final),
        imgsz=imgsz,
        precision="fp16" if fmt == "tensorrt" else "fp32",
        seconds=clock.monotonic() - started,
    )


def export(
    model_name: str,
    formats: Sequence[str] = DEFAULT_FORMATS,
    *,
    imgsz: int | None = None,
    device: str = "cpu",
    registry: ModelRegistry | None = None,
    model_factory: Callable[[str], ExportModel] | None = None,
    clock: Clock | None = None,
) -> ExportResult:
    """Export a registry entry's ``.pt`` weights and register each artefact (spec 6.6).

    Args:
        model_name: Registry name or alias (``ppe_s_latest``, ``pose_n`` ...).
        formats: Any of ``onnx``, ``openvino``, ``tensorrt`` (``engine``/``trt``).
        imgsz: Fixed input size (default: the entry's ``imgsz``).
        device: Device for the ONNX/OpenVINO export; TensorRT always uses a CUDA device.
        registry: Registry to read and update (default ``models/registry.json``).
        model_factory: Loads the weights (default: ``ultralytics.YOLO``; tests pass a fake).
        clock: Time source for timestamps and durations.

    Raises:
        RegistryError: When the name does not resolve.
        ValueError: For an unknown format or an entry whose weights are not ``.pt``.
    """
    registry = registry or ModelRegistry()
    clock = clock or SystemClock()
    factory = model_factory or _load_export_model
    entry = registry.resolve(model_name)
    if entry.format != "pt":
        raise ValueError(f"{entry.name} is a {entry.format!r} model; only .pt weights are exported")
    weights = registry.resolve_path(entry)
    size = imgsz or entry.imgsz
    if size < 32 or size % 32:
        raise ValueError(f"imgsz must be a positive multiple of 32, got {size}")
    artifacts: list[ExportArtifact] = []
    skipped: list[SkippedExport] = []
    for fmt in dict.fromkeys(normalize_format(f) for f in formats):
        reason = export_unavailable_reason(fmt)
        if reason is not None:
            skipped.append(SkippedExport(fmt, reason))
            continue
        artifact = _export_one(
            weights,
            fmt,
            imgsz=size,
            device=_export_device(fmt, device),
            factory=factory,
            clock=clock,
        )
        registry.add_export(
            entry.name, fmt, artifact.path, created_at=clock.now_utc(), sha256=artifact.sha256
        )
        artifacts.append(artifact)
    return ExportResult(entry.name, weights, tuple(artifacts), tuple(skipped))


