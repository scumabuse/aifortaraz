"""Deterministic synthetic YOLO dataset of coloured shapes in the unified taxonomy (spec 6.2).

The dataset proves the training, evaluation and export code end to end without any downloaded
data: every class of :data:`safety_ai.inference.types.TAXONOMY` is drawn as its own combination of
shape (rectangle, ellipse or triangle) and colour on a lightly textured grey background, labelled
in YOLO format and split 80/10/10. The same seed always produces byte-identical files.

Layout written by :func:`generate_synthetic_dataset`::

    <out_dir>/data.yaml
    <out_dir>/images/{train,val,test}/syn_00000.jpg ...
    <out_dir>/labels/{train,val,test}/syn_00000.txt ...

``data.yaml`` has no ``path`` key, so Ultralytics resolves the split directories relative to the
YAML file itself and the dataset can be moved or copied freely.
"""

from __future__ import annotations

import colorsys
import shutil
from collections.abc import Iterator, Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Final, Literal

import cv2
import numpy as np

from safety_ai.capture.types import ImageArray
from safety_ai.inference.types import TAXONOMY

__all__ = [
    "MARKER",
    "SHAPES",
    "SPLITS",
    "ClassStyle",
    "ShapeName",
    "SyntheticObject",
    "class_styles",
    "generate_synthetic_dataset",
    "render_image",
    "split_counts",
]

ShapeName = Literal["rectangle", "ellipse", "triangle"]
SHAPES: Final[tuple[ShapeName, ...]] = ("rectangle", "ellipse", "triangle")
SPLITS: Final[tuple[str, ...]] = ("train", "val", "test")
MARKER: Final[str] = "# generated by safety_ai.training.synthetic"
"""First line of every generated data.yaml; only directories carrying it are ever regenerated."""

_JPEG_QUALITY: Final[int] = 95
_MIN_IMAGES: Final[int] = 10
_MIN_SIDE_PX: Final[int] = 64
_MIN_OBJECTS: Final[int] = 2
_MAX_OBJECTS: Final[int] = 5
_PLACEMENT_ATTEMPTS: Final[int] = 60
_MARGIN_PX: Final[int] = 2
_MIN_BOX_FRACTION: Final[float] = 0.10
_MAX_BOX_FRACTION: Final[float] = 0.32


@dataclass(frozen=True, slots=True)
class ClassStyle:
    """How one taxonomy class is drawn: its shape and its BGR colour."""

    class_id: int
    name: str
    shape: ShapeName
    bgr: tuple[int, int, int]


@dataclass(frozen=True, slots=True)
class SyntheticObject:
    """One drawn object: class id and its pixel box ``[x1, x2) x [y1, y2)``."""

    class_id: int
    x1: int
    y1: int
    x2: int
    y2: int

    def yolo_line(self, width: int, height: int) -> str:
        """Return the YOLO label line ``cls cx cy w h`` (normalized, six decimals)."""
        cx = (self.x1 + self.x2) / 2.0 / width
        cy = (self.y1 + self.y2) / 2.0 / height
        bw = (self.x2 - self.x1) / width
        bh = (self.y2 - self.y1) / height
        return f"{self.class_id} {cx:.6f} {cy:.6f} {bw:.6f} {bh:.6f}"

    def overlaps(self, other: SyntheticObject, margin: int = 0) -> bool:
        """Return True when the two boxes, each grown by ``margin`` pixels, intersect."""
        return not (
            self.x2 + margin <= other.x1
            or other.x2 + margin <= self.x1
            or self.y2 + margin <= other.y1
            or other.y2 + margin <= self.y1
        )


def class_styles() -> tuple[ClassStyle, ...]:
    """Return the drawing style of every taxonomy class, in class-id order.

    Shapes cycle rectangle, ellipse, triangle; hues are spread evenly over the colour wheel in a
    permuted order (so neighbouring class ids get distant hues) with two brightness levels, which
    makes every class distinguishable by colour alone and every (shape, colour) pair unique.
    """
    count = len(TAXONOMY)
    styles: list[ClassStyle] = []
    for class_id, name in enumerate(TAXONOMY):
        hue_slot = (class_id * 7) % count
        value = 1.0 if class_id % 2 == 0 else 0.62
        red, green, blue = colorsys.hsv_to_rgb(hue_slot / count, 0.9, value)
        bgr = (round(blue * 255), round(green * 255), round(red * 255))
        styles.append(ClassStyle(class_id, name, SHAPES[class_id % len(SHAPES)], bgr))
    return tuple(styles)


def split_counts(n_images: int) -> tuple[int, int, int]:
    """Return the ``(train, val, test)`` image counts of an 80/10/10 split of ``n_images``."""
    if n_images < _MIN_IMAGES:
        raise ValueError(f"n_images must be at least {_MIN_IMAGES}, got {n_images}")
    n_val = max(1, round(n_images * 0.1))
    n_test = max(1, round(n_images * 0.1))
    return n_images - n_val - n_test, n_val, n_test


def _split_names(n_images: int, rng: np.random.Generator) -> list[str]:
    """Assign every image index to a split with a seeded permutation."""
    n_train, n_val, _ = split_counts(n_images)
    order = rng.permutation(n_images)
    names = ["test"] * n_images
    for rank, index in enumerate(order.tolist()):
        if rank < n_train:
            names[index] = "train"
        elif rank < n_train + n_val:
            names[index] = "val"
    return names


def _class_cycle(rng: np.random.Generator) -> Iterator[int]:
    """Yield class ids forever as consecutive shuffled permutations of all classes.

    Every block of ``len(TAXONOMY)`` objects therefore contains each class exactly once, so each
    split with at least that many objects represents every class.
    """
    while True:
        yield from (int(c) for c in rng.permutation(len(TAXONOMY)))


def _background(rng: np.random.Generator, width: int, height: int) -> ImageArray:
    """Return a low-saturation grey background with a gentle gradient and pixel noise."""
    base = float(rng.integers(95, 165))
    gx = float(rng.uniform(-25.0, 25.0))
    gy = float(rng.uniform(-25.0, 25.0))
    xs = np.linspace(-0.5, 0.5, width, dtype=np.float64)[None, :]
    ys = np.linspace(-0.5, 0.5, height, dtype=np.float64)[:, None]
    plane = base + gx * xs + gy * ys
    tint = rng.uniform(-6.0, 6.0, size=3)
    noise = rng.normal(0.0, 5.0, size=(height, width, 3))
    image = plane[:, :, None] + tint[None, None, :] + noise
    return np.clip(np.rint(image), 0, 255).astype(np.uint8)


def _random_box(
    rng: np.random.Generator, class_id: int, width: int, height: int
) -> SyntheticObject:
    """Draw a random box with even width/height fully inside the image."""
    short = min(width, height)
    low = max(8, int(short * _MIN_BOX_FRACTION))
    high = max(low + 2, int(short * _MAX_BOX_FRACTION))
    box_w = int(rng.integers(low, high + 1)) // 2 * 2
    box_h = int(rng.integers(low, high + 1)) // 2 * 2
    x1 = int(rng.integers(1, width - box_w))
    y1 = int(rng.integers(1, height - box_h))
    return SyntheticObject(class_id, x1, y1, x1 + box_w, y1 + box_h)


def _draw(image: ImageArray, obj: SyntheticObject, style: ClassStyle, apex_frac: float) -> None:
    """Draw ``obj`` filled with its class style into ``image`` (in place)."""
    colour = style.bgr
    if style.shape == "rectangle":
        cv2.rectangle(image, (obj.x1, obj.y1), (obj.x2 - 1, obj.y2 - 1), colour, cv2.FILLED)
    elif style.shape == "ellipse":
        center = ((obj.x1 + obj.x2) // 2, (obj.y1 + obj.y2) // 2)
        axes = ((obj.x2 - obj.x1) // 2, (obj.y2 - obj.y1) // 2)
        cv2.ellipse(image, center, axes, 0.0, 0.0, 360.0, colour, cv2.FILLED, cv2.LINE_AA)
    else:
        apex_x = obj.x1 + round(apex_frac * (obj.x2 - 1 - obj.x1))
        points = np.array(
            [[obj.x1, obj.y2 - 1], [obj.x2 - 1, obj.y2 - 1], [apex_x, obj.y1]], dtype=np.int32
        )
        cv2.fillPoly(image, [points], colour, cv2.LINE_AA)


def render_image(
    rng: np.random.Generator,
    image_size: tuple[int, int],
    classes: Sequence[int],
    styles: Sequence[ClassStyle] | None = None,
) -> tuple[ImageArray, tuple[SyntheticObject, ...]]:
    """Render one image containing (up to) the requested classes without overlapping objects.

    Objects are placed by rejection sampling; a class that cannot be placed after a bounded number
    of attempts is left out, and only placed objects are returned (they are exactly the labels).

    Args:
        rng: Seeded generator; the result depends only on its state and the arguments.
        image_size: ``(width, height)`` in pixels.
        classes: Class ids to draw, in order.
        styles: Drawing styles indexed by class id (default :func:`class_styles`).

    Returns:
        The BGR image and the placed objects.
    """
    width, height = image_size
    table = tuple(styles) if styles is not None else class_styles()
    image = _background(rng, width, height)
    placed: list[SyntheticObject] = []
    for class_id in classes:
        for _ in range(_PLACEMENT_ATTEMPTS):
            candidate = _random_box(rng, class_id, width, height)
            if not any(candidate.overlaps(other, _MARGIN_PX) for other in placed):
                _draw(image, candidate, table[class_id], float(rng.uniform(0.0, 1.0)))
                placed.append(candidate)
                break
    return image, tuple(placed)


def _data_yaml_text(seed: int, n_images: int, image_size: tuple[int, int]) -> str:
    """Return the data.yaml text (no ``path`` key: splits resolve relative to the file)."""
    width, height = image_size
    lines = [
        MARKER,
        f"# seed {seed}, {n_images} images of {width}x{height} px, split 80/10/10;",
        "# classes = the unified taxonomy (datasets/taxonomy.yaml), one shape/colour per class.",
        "train: images/train",
        "val: images/val",
        "test: images/test",
        f"nc: {len(TAXONOMY)}",
        "names:",
        *(f"  {class_id}: {name}" for class_id, name in enumerate(TAXONOMY)),
    ]
    return "\n".join(lines) + "\n"


def _prepare_out_dir(out_dir: Path) -> None:
    """Create ``out_dir`` or clear a previously generated synthetic dataset inside it.

    A non-empty directory is cleared only when its data.yaml starts with :data:`MARKER`; anything
    else raises FileExistsError so a real dataset is never deleted by mistake.
    """
    if out_dir.exists() and not out_dir.is_dir():
        raise FileExistsError(f"{out_dir} exists and is not a directory")
    if out_dir.is_dir() and any(out_dir.iterdir()):
        yaml_file = out_dir / "data.yaml"
        first_line = ""
        if yaml_file.is_file():
            with yaml_file.open(encoding="utf-8") as handle:
                first_line = handle.readline().rstrip("\r\n")
        if first_line != MARKER:
            raise FileExistsError(
                f"{out_dir} is not empty and does not hold a generated synthetic dataset"
            )
        for sub in ("images", "labels"):
            if (out_dir / sub).exists():
                shutil.rmtree(out_dir / sub)
        yaml_file.unlink()
    out_dir.mkdir(parents=True, exist_ok=True)


def _encode_jpeg(image: ImageArray) -> bytes:
    """Encode a BGR image as JPEG (deterministic for identical input and OpenCV build)."""
    ok, buffer = cv2.imencode(".jpg", image, [cv2.IMWRITE_JPEG_QUALITY, _JPEG_QUALITY])
    if not ok:
        raise RuntimeError("OpenCV failed to encode a synthetic image as JPEG")
    return buffer.tobytes()


def generate_synthetic_dataset(
    out_dir: Path,
    n_images: int = 200,
    seed: int = 0,
    image_size: tuple[int, int] = (320, 240),
) -> Path:
    """Generate the synthetic YOLO dataset and return the path of its ``data.yaml``.

    Args:
        out_dir: Target directory; created when missing. A directory holding an earlier
            generated dataset (data.yaml starting with :data:`MARKER`) is regenerated in place;
            any other non-empty directory raises FileExistsError.
        n_images: Total number of images (at least 10), split 80/10/10 into train/val/test.
        seed: Seed of the generator; identical arguments give byte-identical files.
        image_size: ``(width, height)`` of every image in pixels (each side at least 64).

    Returns:
        The path of the written ``data.yaml`` (``names`` = the unified taxonomy).
    """
    width, height = image_size
    if width < _MIN_SIDE_PX or height < _MIN_SIDE_PX:
        raise ValueError(f"image_size sides must be at least {_MIN_SIDE_PX} px, got {image_size}")
    split_counts(n_images)
    out_dir = Path(out_dir)
    _prepare_out_dir(out_dir)
    for split in SPLITS:
        (out_dir / "images" / split).mkdir(parents=True, exist_ok=True)
        (out_dir / "labels" / split).mkdir(parents=True, exist_ok=True)

    rng = np.random.default_rng(seed)
    splits = _split_names(n_images, rng)
    cycles = {
        split: _class_cycle(np.random.default_rng([seed, i])) for i, split in enumerate(SPLITS)
    }
    styles = class_styles()
    pending: dict[str, list[int]] = {split: [] for split in SPLITS}
    for index, split in enumerate(splits):
        wanted = int(rng.integers(_MIN_OBJECTS, _MAX_OBJECTS + 1))
        queue = pending[split]
        while len(queue) < wanted:
            queue.append(next(cycles[split]))
        image, objects = render_image(rng, (width, height), queue[:wanted], styles)
        placed = [obj.class_id for obj in objects]
        for class_id in placed:
            queue.remove(class_id)
        stem = f"syn_{index:05d}"
        (out_dir / "images" / split / f"{stem}.jpg").write_bytes(_encode_jpeg(image))
        label_text = "".join(obj.yolo_line(width, height) + "\n" for obj in objects)
        (out_dir / "labels" / split / f"{stem}.txt").write_bytes(label_text.encode("ascii"))

    yaml_path = out_dir / "data.yaml"
    yaml_path.write_bytes(_data_yaml_text(seed, n_images, image_size).encode("utf-8"))
    return yaml_path
